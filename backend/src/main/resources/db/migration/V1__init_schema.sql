-- =====================================================================
-- CareRoute schema v1
-- All timestamps are stored as timestamptz (UTC). Enum-like columns are
-- varchar + CHECK constraints so they map cleanly to JPA EnumType.STRING.
-- =====================================================================

-- Health facility that receives referrals (e.g. a Primary Health Centre)
create table facility
(
    id         bigint generated by default as identity primary key,
    name       varchar(160) not null unique,
    type       varchar(20)  not null check (type in ('PHC', 'CHC', 'DISTRICT_HOSPITAL')),
    block      varchar(120) not null,
    created_at timestamptz  not null default now(),
    updated_at timestamptz  not null default now()
);

-- Village served by one referral facility
create table village
(
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null unique,
    block       varchar(120) not null,
    district    varchar(120) not null,
    facility_id bigint       not null references facility (id),
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now()
);

create table app_user
(
    id            bigint generated by default as identity primary key,
    username      varchar(60)  not null unique,
    password_hash varchar(100) not null,
    full_name     varchar(120) not null,
    role          varchar(20)  not null check (role in ('ASHA', 'PHC_STAFF', 'SUPERVISOR')),
    phone         varchar(20),
    village_id    bigint references village (id),
    facility_id   bigint references facility (id),
    active        boolean      not null default true,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint chk_user_scope check (
        (role = 'ASHA' and village_id is not null)
            or (role = 'PHC_STAFF' and facility_id is not null)
            or (role = 'SUPERVISOR')
        )
);

create table patient
(
    id            bigint generated by default as identity primary key,
    full_name     varchar(120) not null,
    age           integer      not null check (age between 0 and 120),
    sex           varchar(10)  not null check (sex in ('FEMALE', 'MALE', 'OTHER')),
    phone         varchar(20),
    program       varchar(30)  not null check (program in ('MATERNAL', 'TB', 'CHILD_IMMUNIZATION', 'NCD')),
    village_id    bigint       not null references village (id),
    asha_id       bigint       not null references app_user (id),
    consent_given boolean      not null,
    consent_at    timestamptz,
    notes         text,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now()
);
create index idx_patient_asha on patient (asha_id);
create index idx_patient_village on patient (village_id);

-- Configurable, transparent follow-up / referral rule.
-- condition example: {"match":"ANY","clauses":[{"field":"SYSTOLIC_BP","op":"GTE","value":140}]}
create table care_rule
(
    id               bigint generated by default as identity primary key,
    code             varchar(60)  not null unique,
    name             varchar(160) not null,
    program          varchar(30) check (program in ('MATERNAL', 'TB', 'CHILD_IMMUNIZATION', 'NCD')),
    condition        jsonb        not null,
    action           varchar(20)  not null check (action in ('FOLLOW_UP', 'REFERRAL')),
    priority         varchar(10)  not null check (priority in ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    due_within_hours integer      not null check (due_within_hours between 1 and 2160),
    explanation      text         not null,
    active           boolean      not null default true,
    created_at       timestamptz  not null default now(),
    updated_at       timestamptz  not null default now()
);

-- Screening observations recorded during a home visit (not a diagnosis)
create table visit
(
    id              bigint generated by default as identity primary key,
    patient_id      bigint      not null references patient (id),
    asha_id         bigint      not null references app_user (id),
    visited_at      timestamptz not null,
    systolic_bp     integer check (systolic_bp between 50 and 260),
    diastolic_bp    integer check (diastolic_bp between 30 and 180),
    weight_kg       numeric(5, 2),
    temperature_c   numeric(4, 1),
    pregnancy_weeks integer check (pregnancy_weeks between 1 and 45),
    dose_taken      boolean,
    symptoms        jsonb       not null default '[]'::jsonb,
    notes           text,
    source          varchar(10) not null default 'MANUAL' check (source in ('MANUAL', 'VOICE')),
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);
create index idx_visit_patient on visit (patient_id, visited_at desc);

create table referral
(
    id              bigint generated by default as identity primary key,
    patient_id      bigint      not null references patient (id),
    visit_id        bigint references visit (id),
    rule_id         bigint references care_rule (id),
    facility_id     bigint      not null references facility (id),
    referred_by     bigint      not null references app_user (id),
    reason          text        not null,
    priority        varchar(10) not null check (priority in ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    status          varchar(15) not null check (status in ('REFERRED', 'ACKNOWLEDGED', 'ARRIVED', 'CLOSED')),
    due_at          timestamptz not null,
    acknowledged_at timestamptz,
    arrived_at      timestamptz,
    closed_at       timestamptz,
    escalated_at    timestamptz,
    outcome_note    text,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);
create index idx_referral_patient on referral (patient_id);
create index idx_referral_facility_status on referral (facility_id, status);
create index idx_referral_open_due on referral (due_at) where status in ('REFERRED', 'ACKNOWLEDGED');

-- Immutable timeline of what happened to a referral
create table referral_event
(
    id          bigint generated by default as identity primary key,
    referral_id bigint      not null references referral (id),
    event_type  varchar(20) not null check (event_type in ('REFERRED', 'ACKNOWLEDGED', 'ARRIVED', 'CLOSED', 'ESCALATED')),
    actor_id    bigint references app_user (id),
    note        text,
    occurred_at timestamptz not null,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);
create index idx_referral_event_referral on referral_event (referral_id, occurred_at);

-- Task on an ASHA's due list
create table follow_up
(
    id           bigint generated by default as identity primary key,
    patient_id   bigint      not null references patient (id),
    assigned_to  bigint      not null references app_user (id),
    visit_id     bigint references visit (id),
    rule_id      bigint references care_rule (id),
    referral_id  bigint references referral (id),
    reason       text        not null,
    priority     varchar(10) not null check (priority in ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    due_at       timestamptz not null,
    status       varchar(15) not null check (status in ('PENDING', 'COMPLETED', 'CANCELLED')),
    completed_at timestamptz,
    completion_note text,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now()
);
create index idx_follow_up_assignee_status on follow_up (assigned_to, status, due_at);
create index idx_follow_up_patient on follow_up (patient_id);

-- Who touched which record (privacy accountability)
create table audit_log
(
    id          bigint generated by default as identity primary key,
    actor_id    bigint references app_user (id),
    action      varchar(40) not null,
    entity_type varchar(40) not null,
    entity_id   bigint,
    details     text,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);
create index idx_audit_entity on audit_log (entity_type, entity_id, created_at desc);
